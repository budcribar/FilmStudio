/**
 * Tiny valid-enough MPEG audio frame stream for mock TTS / clone output.
 * Not musical — exists so <audio> and client FFmpeg can treat it as audio/mpeg.
 */

/** One MPEG1 Layer III frame (~26ms at 44.1kHz, 32kbps, mono) — silence. */
const MP3_FRAME = Uint8Array.from([
  0xff, 0xfb, 0x10, 0xc4, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
]);

/** ~durationSec of repeated frames (mock clone / line read). */
export function buildMockMp3Blob(durationSec = 1.2): Blob {
  const framesNeeded = Math.max(8, Math.ceil(durationSec / 0.026));
  const parts: Uint8Array[] = [];
  for (let i = 0; i < framesNeeded; i++) parts.push(MP3_FRAME);
  const total = parts.reduce((n, p) => n + p.length, 0);
  const out = new Uint8Array(total);
  let o = 0;
  for (const p of parts) {
    out.set(p, o);
    o += p.length;
  }
  return new Blob([out], { type: "audio/mpeg" });
}
